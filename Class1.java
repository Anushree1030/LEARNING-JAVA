// How to run java code?
// 1. Compiletion:-
// source code (.java) -> compiler (present in JDK) -> byte code(.class)

// Byte code can run in every system that is why JAVA is called portable language. C++ can't run in any system, it needs a specific platform to run.

// JDK (Java Development Kit)
// Used to develop, compile, and run java programs.
//         |
// JRE (Java Runtime Enviroment) + Development tools
// Used to run java programs.
//         |
// JVM (Java Virtual Machine)
// executes bytecodes.

// 2.Execution:-
// Byte code -> JVM -> Native code

// Native code:- A language that computer understands.(binary 0,1)
